"""
Inspect existing NetSentinels model artifacts.

This script does not train or modify any model.
Only load joblib files created by your own trusted project.
"""

from pathlib import Path

import joblib


PROJECT_ROOT = Path(__file__).resolve().parent.parent
MODEL_DIR = PROJECT_ROOT / "models"


def inspect_object(name, obj):
    print("\n" + "=" * 70)
    print(f"ARTIFACT: {name}")
    print("=" * 70)
    print("Python type:", type(obj).__name__)

    if isinstance(obj, dict):
        print("Dictionary keys:", list(obj.keys()))

        for key, value in obj.items():
            print(f"\n[{key}]")
            print("Type:", type(value).__name__)

            if hasattr(value, "n_features_in_"):
                print("Expected feature count:", value.n_features_in_)

            if hasattr(value, "feature_names_in_"):
                print(
                    "Expected feature names:",
                    list(value.feature_names_in_),
                )

            if hasattr(value, "classes_"):
                print("Classes:", value.classes_)

    else:
        if hasattr(obj, "n_features_in_"):
            print("Expected feature count:", obj.n_features_in_)

        if hasattr(obj, "feature_names_in_"):
            print(
                "Expected feature names:",
                list(obj.feature_names_in_),
            )

        if hasattr(obj, "named_steps"):
            print("Pipeline steps:", list(obj.named_steps.keys()))

        if hasattr(obj, "classes_"):
            print("Classes:", obj.classes_)

        if hasattr(obj, "estimators_"):
            print("Number of estimators:", len(obj.estimators_))


def main():
    if not MODEL_DIR.exists():
        print(f"Model directory not found: {MODEL_DIR}")
        return

    model_files = [
        MODEL_DIR / "hybrid_model.joblib",
        MODEL_DIR / "isolation_forest.joblib",
    ]

    for model_path in model_files:
        if not model_path.exists():
            print(f"\nMissing model: {model_path.name}")
            continue

        try:
            # joblib can execute code during deserialization.
            # Load only artifacts generated by your trusted project.
            model = joblib.load(model_path)
            inspect_object(model_path.name, model)

        except Exception as exc:
            print(f"\nCould not inspect {model_path.name}: {exc}")


if __name__ == "__main__":
    main()